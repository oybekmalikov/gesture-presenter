// API-first runtime engine with static-DICTIONARY fallback
const API_BASE = (window.SAFEGUARD_API_URL || '') + '/api';
const _translationsCache = {};
let currentLang = localStorage.getItem('safeguard_lang') || 'uz';

async function fetchTranslations(locale) {
  if (_translationsCache[locale]) return _translationsCache[locale];
  try {
    const res = await fetch(API_BASE + '/i18n/' + locale,
      {});
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const data = await res.json();
    // DB bo'sh bo'lsa (yangi o'rnatish) — static lug'atni fallback sifatida ishlatamiz
    if (data.strings && Object.keys(data.strings).length > 0) {
      _translationsCache[locale] = data.strings;
    } else {
      _translationsCache[locale] = (DICTIONARY[locale] && DICTIONARY[locale].strings) || {};
    }
    return _translationsCache[locale];
  } catch (err) {
    console.warn('[i18n] API unavailable for ' + locale + ', using static dict.');
    _translationsCache[locale] = (DICTIONARY[locale] && DICTIONARY[locale].strings) || {};
    return _translationsCache[locale];
  }
}

async function preloadAllLocales() {
  await Promise.all(['en','ru','uz'].map(fetchTranslations));
}

