async function setLanguage(langCode, event) {
  if (event) event.stopPropagation();
  if (!DICTIONARY[langCode]) return;
  currentLang = langCode;
  localStorage.setItem('safeguard_lang', langCode);
  await fetchTranslations(langCode);
  const switcher = document.getElementById('langSwitcher');
  if (switcher) {
    const fl = switcher.querySelector('.lang-current .lang-flag');
    if (fl) fl.innerHTML = FLAG_SVG[langCode] || '';
    switcher.querySelector('.lang-current .lang-text').textContent = DICTIONARY[langCode].name;
    switcher.classList.remove('open');
  }
  applyTranslations();
}

function applyTranslations() {
  const dict  = _translationsCache[currentLang] || (DICTIONARY[currentLang] && DICTIONARY[currentLang].strings) || {};
  const enMap = _translationsCache['en'] || (DICTIONARY['en'] && DICTIONARY['en'].strings) || {};
  const ruMap = _translationsCache['ru'] || (DICTIONARY['ru'] && DICTIONARY['ru'].strings) || {};
  const uzMap = _translationsCache['uz'] || (DICTIONARY['uz'] && DICTIONARY['uz'].strings) || {};

  function toEngKey(text) {
    if (enMap[text]) return text;
    for (const [k, v] of Object.entries(ruMap)) { if (v === text) return k; }
    for (const [k, v] of Object.entries(uzMap)) { if (v === text) return k; }
    return null;
  }

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while ((node = walker.nextNode())) {
    const text = node.nodeValue.trim();
    if (!text) continue;
    const engKey = toEngKey(text);
    if (engKey && dict[engKey]) node.nodeValue = node.nodeValue.replace(text, dict[engKey]);
  }

  document.querySelectorAll('input[placeholder]').forEach(function(input) {
    const text   = input.getAttribute('placeholder');
    const engKey = toEngKey(text);
    if (engKey && dict[engKey]) input.setAttribute('placeholder', dict[engKey]);
  });
}

window.addEventListener('DOMContentLoaded', async function() {
  await preloadAllLocales();
  const fl = document.querySelector('#langSwitcher .lang-current .lang-flag');
  if (fl) fl.innerHTML = FLAG_SVG[currentLang] || '';
  setLanguage(currentLang);
});
